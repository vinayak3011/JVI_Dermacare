-- Run this in Supabase SQL Editor for a hosted DermCare data store.
-- Storage is intentionally separate: create a private bucket named dermcare-scans
-- and keep image object paths in scans.image_path.

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null unique,
  location text not null default '',
  phone text not null default '',
  age integer not null check (age between 1 and 120),
  date_of_birth date not null,
  password_hash text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.scans (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  subject_name text not null default 'My skin scan',
  image_path text not null,
  original_filename text not null,
  predictions jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists scans_user_created_idx on public.scans(user_id, created_at desc);
alter table public.users enable row level security;
alter table public.scans enable row level security;

